#define VM_OPS_PER_FRAME  100000  /* ~6M insts / sec */

static void call_fn(lua_State *L, const char *name) {
    lua_getglobal(L, name);
    if (!lua_isfunction(L, -1)) { lua_pop(L, 1); return; }
    if (lua_pcall(L, 0, 0, 0) != LUA_OK) {
        fprintf(stderr, "%s: %s\n", name, lua_tostring(L, -1));
        lua_pop(L, 1);
    }
}

// simple hot reload for boot.lua and sources
static time_t last_sources_mtime = 0;
static time_t last_mtime = 0;

static bool cart_changed(const char *path) {
    struct stat s;
    if (stat(path, &s) != 0) return false;
    if (s.st_mtime != last_mtime) {
        last_mtime = s.st_mtime;
        return last_mtime != 0;   /* skip first frame */
    }
    return false;
}

// i know it looks exactly the same but i promised it prevents a segfault
static bool folder_changed(const char *path, time_t *tracked_time) {
    struct stat s;
    if (stat(path, &s) != 0) return false;
    if (s.st_mtime != *tracked_time) {
        *tracked_time = s.st_mtime;
        return *tracked_time != 0;   /* Skip the first initialization frame */
    }
    return false;
}

void vm_reload(VM *vm, const char *path) {
    bool boot_changed = cart_changed(path);
    bool modules_changed = folder_changed("sources", &last_sources_mtime);

    // If EITHER has a legitimate structural modification, trigger the reboot
    if (boot_changed || modules_changed) {
        vm_shutdown(vm);  
        vm_init(vm);      
        vm_load(vm, path);
    }
}

static int  g_ops       = 0;
static bool g_cpu_limit = false;

static void cpu_hook(lua_State *L, lua_Debug *ar) {
    (void)ar;
    g_ops += 100;   /* hook fires every 100 ops */
    if (g_ops >= VM_OPS_PER_FRAME) {
        g_cpu_limit = true;
        luaL_error(L, "MAXIMUM CPU LEVEL REACHED");
        lua_yield(L, 0); // hooked to nothing rn
    }
}

static void register_source(lua_State *L) {
    // Force-inject "sources/" into Lua's package search path environment
    lua_getglobal(L, "package");
    lua_getfield(L, -1, "path");
    const char* current_path = lua_tostring(L, -1);

    char new_path[1024];
    // Append both standard file layouts and folder init structures
    snprintf(new_path, sizeof(new_path), "%s;sources/?.lua;sources/?/init.lua", current_path);

    lua_pop(L, 1); // Pop the old path string
    lua_pushstring(L, new_path);
    lua_setfield(L, -2, "path"); // package.path = new_path
    lua_pop(L, 1); // Pop the package table

}

void vm_init(VM *vm) {
    vm->L = luaL_newstate();
    // globalize lua's libc/libm
    luaL_openlibs(vm->L);
    // set cpu limit (6 mips)
    lua_sethook(vm->L, cpu_hook, LUA_MASKCOUNT, 100);
    // register and globalize API
    api_register(vm->L);
    // adds sources to package search path
    register_source(vm->L);
    
}

void vm_load(VM *vm, const char *path) {
  
    if (luaL_dofile(vm->L, path) != LUA_OK) {
        fprintf(stderr, "vm_load: %s\n", lua_tostring(vm->L, -1));
        lua_pop(vm->L, 1);
    }
    
    call_fn(vm->L, "_boot");
}

void vm_update  (VM *vm) { 
    g_ops       = 0;
    g_cpu_limit = false;
    call_fn(vm->L, "_tick"); 
}
void vm_shutdown(VM *vm) { 
    lua_close(vm->L); 
}

void vm_bios(VM *vm) {
    if (luaL_loadbuffer(vm->L, (const char*)bios_rom, bios_rom_len, "BIOS") != LUA_OK) {
        printf("Error loading BIOS somehow: %s\n", lua_tostring(vm->L, -1));
        lua_close(vm->L);
    }

    // 3. Execute the bytecode
    if (lua_pcall(vm->L, 0, LUA_MULTRET, 0) != LUA_OK) {
        printf("Error running BIOS somehow: %s\n", lua_tostring(vm->L, -1));
        lua_close(vm->L);
    }
}

